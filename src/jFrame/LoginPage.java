     //validation
     public boolean validateLogin(){
         
         String pwd=txt_password.getText();
         String email=txt_email.getText();
        
         
         
         if(pwd.equals(""))
         {
             JOptionPane.showMessageDialog(this,"please enter password");
             return false;
         }
         if(email.equals("")|| !email.matches("^.+@.+\\..+$"))
         {
             JOptionPane.showMessageDialog(this,"please enter valid email");
             return false;
         }
         
         return true;
     }
     
     //verify creds
     public void login(){
         String pwd=txt_password.getText();
         String email=txt_email.getText();
         java.sql.PreparedStatement pst=null;
        ResultSet rs=null;
         
         try{
              Connection conn=DriverManager.getConnection("jdbc:mysql://localhost:3306/library_ms","root","arjun");
               pst=conn.prepareStatement("select * from user where email=? and password=?");
              pst.setString(1,email);
              pst.setString(2, pwd);
             rs= pst.executeQuery();
             
             if(rs.next()){
                 JOptionPane.showMessageDialog(this,"Login Successfull");
                 new Homepage().setVisible(true);
                 this.setVisible(false);
             }
             else{
                  JOptionPane.showMessageDialog(this,"Email or Password are Incorrect.Please Enter Valid Email or Password.");
             }
             
             
         }
         catch(HeadlessException | SQLException e){
             System.out.println(e);
         }
     }
    
     
